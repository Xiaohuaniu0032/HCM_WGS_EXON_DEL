#!/usr/bin/env python3
import argparse
import os
import re
import pandas as pd
import matplotlib.pyplot as plt

REGION_RE = re.compile(r"^(?P<chr>[^:]+):(?P<start>\d+)-(?P<end>\d+)$")


def parse_windows_section(infile: str) -> pd.DataFrame:
    """
    Parse the === WINDOWS === section.

    Supports two formats:
      A) WinIndex  Chr   Start  End   ... RatioToGeneMean (parts[5])
      B) WinIndex  Region(chr:start-end) ... RatioToGeneMean (parts[5])
         (i.e., the "Chr" column actually stores region string)
    """
    rows = []
    in_windows = False

    with open(infile, "r", encoding="utf-8", errors="replace") as f:
        it = iter(f)
        for line in it:
            line = line.rstrip("\n")

            if line.strip() == "=== WINDOWS ===":
                in_windows = True
                # Skip header line right after the section tag
                try:
                    next(it)
                except StopIteration:
                    break
                continue

            if not in_windows:
                continue

            if not line.strip():
                continue
            if line.startswith("==="):
                break

            parts = line.split("\t")
            if len(parts) < 6:
                continue

            try:
                win = int(parts[0])
                ratio = float(parts[5])

                # Case B: parts[1] looks like "chr18:34232676-34233675"
                m = REGION_RE.match(parts[1])
                if m:
                    chrom = m.group("chr")
                    start = int(m.group("start"))
                    end = int(m.group("end"))
                else:
                    # Case A: normal columns
                    chrom = parts[1]
                    start = int(parts[2])
                    end = int(parts[3])

                rows.append({
                    "WinIndex": win,
                    "Chr": chrom,          # normalized chromosome only (e.g. chr18)
                    "Start": start,
                    "End": end,
                    "RatioToGeneMean": ratio,
                })
            except ValueError:
                continue

    df = pd.DataFrame(rows)
    if df.empty:
        return df
    return df.sort_values("WinIndex").reset_index(drop=True)


def _build_segment(df: pd.DataFrame, start_i: int, end_i: int) -> dict:
    seg = df.iloc[start_i:end_i + 1]
    chroms = seg["Chr"].unique()
    chr_str = chroms[0] if len(chroms) == 1 else f"{chroms[0]}(MULTI)"

    return {
        "chr": chr_str,
        "start_bp": int(seg["Start"].min()),
        "end_bp": int(seg["End"].max()),
        "start_win": int(seg["WinIndex"].iloc[0]),
        "end_win": int(seg["WinIndex"].iloc[-1]),
        "n": int(len(seg)),
        "mean_ratio": float(seg["RatioToGeneMean"].mean()),
    }


def find_consecutive_segments(df: pd.DataFrame, low: float, high: float, min_windows: int = 2):
    """
    Find consecutive WinIndex segments where RatioToGeneMean in [low, high].
    """
    if df.empty:
        return []

    w = df["WinIndex"].to_numpy()
    y = df["RatioToGeneMean"].to_numpy()
    mask = (y >= low) & (y <= high)

    segs = []
    start_i = None

    for i in range(len(w)):
        if mask[i] and start_i is None:
            start_i = i
        elif (not mask[i]) and start_i is not None:
            end_i = i - 1
            seg = _build_segment(df, start_i, end_i)
            if seg["n"] >= min_windows:
                segs.append(seg)
            start_i = None

    if start_i is not None:
        end_i = len(w) - 1
        seg = _build_segment(df, start_i, end_i)
        if seg["n"] >= min_windows:
            segs.append(seg)

    return segs


def format_segments_for_text_en(segs, max_lines=5):
    """
    Short annotation: only merged genomic start-end per segment (plus WinIndex range).
    """
    if not segs:
        return "CNV candidates: None"

    lines = ["CNV candidates (merged):"]
    for s in segs[:max_lines]:
        lines.append(
            f"- {s['chr']}:{s['start_bp']}-{s['end_bp']} | "
            f"Win {s['start_win']}-{s['end_win']} | "
            f"n={s['n']} | mean={s['mean_ratio']:.3f}"
        )
    if len(segs) > max_lines:
        lines.append(f"... +{len(segs) - max_lines} more")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(
        description="Plot RatioToGeneMean from === WINDOWS === section with CNV candidate segments."
    )
    parser.add_argument("infile", help="Depth report file generated by Perl script")
    parser.add_argument("--low", type=float, default=0.4, help="Lower bound (default=0.4)")
    parser.add_argument("--high", type=float, default=0.6, help="Upper bound (default=0.6)")
    parser.add_argument("--threshold", type=float, default=0.5, help="Threshold line (default=0.5)")
    parser.add_argument("--min_windows", type=int, default=2, help="Min consecutive windows to report (default=2)")
    parser.add_argument("--out", help="Output png file (optional)")
    args = parser.parse_args()

    infile = args.infile
    low, high, threshold = args.low, args.high, args.threshold

    out_png = args.out if args.out else (
        os.path.basename(infile).replace(".tsv", "").replace(".txt", "") + ".windows_ratio.png"
    )

    df = parse_windows_section(infile)
    if df.empty:
        raise SystemExit("ERROR: No WINDOWS section detected. Check file format.")

    x = df["WinIndex"].to_numpy()
    y = df["RatioToGeneMean"].to_numpy()
    mask_hit = (y >= low) & (y <= high)

    segs = find_consecutive_segments(df, low=low, high=high, min_windows=args.min_windows)

    # Print merged intervals
    if segs:
        print("CNV candidate segments (merged):")
        print("Chr\tStart\tEnd\tWinStart\tWinEnd\tNwin\tMeanRatio")
        for s in segs:
            print(f"{s['chr']}\t{s['start_bp']}\t{s['end_bp']}\t{s['start_win']}\t{s['end_win']}\t{s['n']}\t{s['mean_ratio']:.4f}")
    else:
        print("CNV candidate segments: None")

    # Plot
    fig, ax = plt.subplots(figsize=(12, 4.5))

    ax.axhspan(low, high, alpha=0.12, zorder=0)
    ax.plot(x, y, linewidth=1.1, zorder=1)
    ax.scatter(x, y, s=22, zorder=2)
    if mask_hit.any():
        ax.scatter(x[mask_hit], y[mask_hit], s=42, color="red", zorder=3)

    ax.axhline(threshold, linestyle="--", linewidth=1)
    ax.axhline(low, linestyle="--", linewidth=1)
    ax.axhline(high, linestyle="--", linewidth=1)

    ax.text(1.01, threshold, f"threshold={threshold:g}",
            transform=ax.get_yaxis_transform(),
            va="center", ha="left", fontsize=9)
    ax.text(1.01, low, f"low={low:g}",
            transform=ax.get_yaxis_transform(),
            va="center", ha="left", fontsize=9)
    ax.text(1.01, high, f"high={high:g}",
            transform=ax.get_yaxis_transform(),
            va="center", ha="left", fontsize=9)

    ax.set_xlabel("WinIndex")
    ax.set_ylabel("RatioToGeneMean")
    ax.set_title(os.path.basename(infile))
    ax.set_ylim(bottom=0)

    # Annotation box (bottom-left)
    ann = format_segments_for_text_en(segs)
    ax.text(
        0.02, 0.02, ann,
        transform=ax.transAxes,
        va="bottom", ha="left",
        fontsize=10,
        bbox=dict(boxstyle="round,pad=0.3", facecolor="white", alpha=0.85, linewidth=0.8)
    )

    fig.tight_layout()
    fig.savefig(out_png, dpi=200)
    print("Saved:", out_png)


if __name__ == "__main__":
    main()


