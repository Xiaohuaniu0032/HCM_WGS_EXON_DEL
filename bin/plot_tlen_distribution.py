#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
Script: plot_tlen_distribution.py

Purpose:
    Plot Insert Size / TLEN distribution from a TSV file generated by extract_valid_tlen.pl.

Input format:
    ReadName    TLEN
    read_1      386
    read_2      402
    read_3      395

Usage:
    python plot_tlen_distribution.py <input_tlen_tsv> <output_pdf_or_png>

Example:
    python plot_tlen_distribution.py \
        /data/WGS/sample.valid_tlen.tsv \
        /data/WGS/sample.tlen_distribution.pdf

Output:
    1) Insert Size / TLEN distribution plot
    2) Summary statistics file: <output>.summary.tsv

Requirements:
    pandas
    numpy
    matplotlib
"""

import sys
import os
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt


def usage():
    print(
        "Usage: python plot_tlen_distribution.py "
        "<input_tlen_tsv> <output_pdf_or_png>",
        file=sys.stderr
    )
    sys.exit(1)


def calculate_mad(values, median_value):
    """
    MAD = median(|xi - median(x)|)
    """
    deviations = np.abs(values - median_value)
    return np.median(deviations)


def main():
    if len(sys.argv) != 3:
        usage()

    input_file = sys.argv[1]
    output_fig = sys.argv[2]

    if not os.path.exists(input_file):
        raise FileNotFoundError(f"[ERROR] Input file does not exist: {input_file}")

    if not os.path.isabs(input_file):
        raise ValueError(f"[ERROR] Input file must be an absolute path: {input_file}")

    if not os.path.isabs(output_fig):
        raise ValueError(f"[ERROR] Output figure path must be an absolute path: {output_fig}")

    # -----------------------------
    # Read TLEN file
    # -----------------------------
    df = pd.read_csv(input_file, sep="\t")

    if "TLEN" not in df.columns:
        raise ValueError("[ERROR] Input file must contain a column named 'TLEN'")

    df["TLEN"] = pd.to_numeric(df["TLEN"], errors="coerce")
    df = df.dropna(subset=["TLEN"])

    # Only keep positive TLEN values
    # Positive TLEN avoids counting the same paired-end fragment twice
    df = df[df["TLEN"] > 0]

    if df.empty:
        raise ValueError("[ERROR] No valid positive TLEN values found.")

    tlen = df["TLEN"].values

    # -----------------------------
    # Calculate statistics
    # -----------------------------
    total_count = len(tlen)

    mean_insert_size = np.mean(tlen)
    sd_insert_size = np.std(tlen, ddof=1)

    median_insert_size = np.median(tlen)
    mad = calculate_mad(tlen, median_insert_size)

    mad_scale = 1.4826
    robust_sd = mad_scale * mad

    n_mad = 3
    abnormal_tlen_threshold = median_insert_size + n_mad * robust_sd

    q1 = np.percentile(tlen, 25)
    q3 = np.percentile(tlen, 75)
    p95 = np.percentile(tlen, 95)
    p99 = np.percentile(tlen, 99)

    # -----------------------------
    # Filter extreme tail for visualization
    # -----------------------------
    # Statistics are calculated using all TLEN values.
    # The plot only displays values <= P99.5 to make the main distribution clearer.
    plot_upper = np.percentile(tlen, 99.5)
    tlen_for_plot = tlen[tlen <= plot_upper]

    # -----------------------------
    # Plot
    # -----------------------------
    fig, ax = plt.subplots(figsize=(9, 5.5))

    ax.hist(
        tlen_for_plot,
        bins=100,
        alpha=0.85,
        edgecolor="black",
        linewidth=0.3
    )

    ax.axvline(
        median_insert_size,
        linestyle="--",
        linewidth=1.5,
        label=f"Median = {median_insert_size:.1f} bp"
    )

    ax.axvline(
        abnormal_tlen_threshold,
        linestyle="--",
        linewidth=1.5,
        label=f"Threshold = {abnormal_tlen_threshold:.1f} bp"
    )

    ax.set_xlabel("Insert Size / TLEN (bp)")
    ax.set_ylabel("Read pair count")

    subtitle = (
        f"N = {total_count:,} | "
        f"Median = {median_insert_size:.1f} bp | "
        f"MAD = {mad:.1f} | "
        f"Robust SD = {robust_sd:.1f} | "
        f"Threshold = {abnormal_tlen_threshold:.1f} bp | "
        f"Plot ≤ P99.5 = {plot_upper:.1f} bp"
    )

    ax.set_title(
        subtitle,
        fontsize=9,
        pad=5
    )

    ax.legend(loc="upper right", frameon=True)

    # Top space is reduced because the main title has been removed
    fig.tight_layout(rect=[0, 0, 1, 0.98])

    fig.savefig(output_fig, dpi=300)
    plt.close(fig)

    # -----------------------------
    # Output summary statistics
    # -----------------------------
    summary_file = output_fig + ".summary.tsv"

    with open(summary_file, "w") as out:
        out.write(
            "\t".join([
                "Input_File",
                "Total_Read_Pairs",
                "Mean_Insert_Size",
                "SD_Insert_Size",
                "Median_Insert_Size",
                "MAD",
                "MAD_Scale",
                "Robust_SD",
                "N_MAD",
                "Abnormal_TLEN_Threshold",
                "Q1",
                "Q3",
                "P95",
                "P99",
                "Plot_Upper_P99_5"
            ]) + "\n"
        )

        out.write(
            "\t".join([
                input_file,
                str(total_count),
                f"{mean_insert_size:.3f}",
                f"{sd_insert_size:.3f}",
                f"{median_insert_size:.3f}",
                f"{mad:.3f}",
                f"{mad_scale:.4f}",
                f"{robust_sd:.3f}",
                str(n_mad),
                f"{abnormal_tlen_threshold:.3f}",
                f"{q1:.3f}",
                f"{q3:.3f}",
                f"{p95:.3f}",
                f"{p99:.3f}",
                f"{plot_upper:.3f}"
            ]) + "\n"
        )

    print("[INFO] Done.")
    print(f"[INFO] Input: {input_file}")
    print(f"[INFO] Output figure: {output_fig}")
    print(f"[INFO] Summary file: {summary_file}")
    print(f"[INFO] Total read pairs: {total_count:,}")
    print(f"[INFO] Mean insert size: {mean_insert_size:.3f}")
    print(f"[INFO] SD insert size: {sd_insert_size:.3f}")
    print(f"[INFO] Median insert size: {median_insert_size:.3f}")
    print(f"[INFO] MAD: {mad:.3f}")
    print(f"[INFO] Robust SD: {robust_sd:.3f}")
    print(f"[INFO] Abnormal TLEN threshold: {abnormal_tlen_threshold:.3f}")


if __name__ == "__main__":
    main()


    