sub validate_cusum_params {
    my ($cusum_ref) = @_;

    foreach my $key (qw(bin_size k h edge_ratio recover_ratio recover_bins del_ratio min_bins min_len)) {
        die "[ERROR] Empty CUSUM parameter: $key\n"
            unless exists $cusum_ref->{$key}
            && defined $cusum_ref->{$key}
            && $cusum_ref->{$key} ne "";
    }

    die "[ERROR] CUSUM_BASELINE cannot be empty\n"
        unless exists $cusum_ref->{baseline}
        && defined $cusum_ref->{baseline}
        && $cusum_ref->{baseline} ne "";

    if ($cusum_ref->{baseline} ne "auto") {
        die "[ERROR] CUSUM_BASELINE must be 'auto' or a numeric value: $cusum_ref->{baseline}\n"
            unless is_number($cusum_ref->{baseline});
    }

    foreach my $key (qw(k h edge_ratio recover_ratio del_ratio)) {
        die "[ERROR] CUSUM parameter $key must be numeric: $cusum_ref->{$key}\n"
            unless is_number($cusum_ref->{$key});
    }

    foreach my $key (qw(bin_size recover_bins min_bins min_len)) {
        die "[ERROR] CUSUM parameter $key must be a positive integer: $cusum_ref->{$key}\n"
            unless $cusum_ref->{$key} =~ /^\d+$/ && $cusum_ref->{$key} > 0;
    }

    return 1;
}

sub is_number {
    my ($v) = @_;

    return 0 unless defined $v;
    return $v =~ /^-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?$/ ? 1 : 0;
}

