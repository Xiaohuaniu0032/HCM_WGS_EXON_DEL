#!/usr/bin/env perl
# -*- coding: utf-8 -*-

use strict;
use warnings;
use Getopt::Long;
use File::Path qw(make_path);
use Cwd qw(abs_path);
use FindBin qw($Bin);
use File::Basename qw(dirname);

# ============================================================
# HCMExonDel main pipeline
#
# Function:
#   Generate one shell script for each BAM sample.
#
# Input:
#   1. Config file
#   2. BAM list, two TAB-delimited columns:
#      column 1: sample name
#      column 2: absolute BAM path
#
# Output:
#   OUTDIR/SAMPLE/SAMPLE.run.sh
#
# Workflow:
#   1.  run_gene_mean_depth.pl
#   1b. cusum_depth_del.pl
#   1c. calc_depth_ratio.pl
#   1d. plot_depth_ratio.py
#   2.  extract_sa_split_reads.pl
#   3.  cluster_sa_split_reads.pl
#   3b. extract_valid_tlen.pl
#   3c. plot_tlen_distribution.py
#   4.  run_discordant_reads.pl
#   5.  merge_evidence.pl
#   6.  extract_candidate_gene_bam.pl
#   7.  annotate_candidates.pl
#
# Notes:
#   1. No sample_shell.list is generated.
#   2. No qsub_command.list is generated.
#   3. THREADS is not read from config.
#   4. No --threads is passed to run_gene_mean_depth.pl.
#   5. Generated shell commands do not use single quotes around paths.
#   6. Candidate gene BAM extraction is always generated.
#   7. No flank is passed to extract_candidate_gene_bam.pl.
#      The extraction script uses its internal default flank = 0.
#   8. CUSUM and calc_depth_ratio steps use per-gene depth files.
#      Therefore KEEP_GENE_DEPTH_FILE must be 1.
#   9. CUSUM_BASELINE, CUSUM_K and CUSUM_H must be set in config.
#      These three parameters can only be modified from the config file.
#  10. In SAMPLE.run.sh, Step 1b and Step 1c are simple bash
#      step-script commands. Looping and merging logic is written into:
#        tmp/SAMPLE.step1b.cusum_depth_del.sh
#        tmp/SAMPLE.step1c.calc_depth_ratio.sh
#  11. Step 1b skips all-zero depth files to avoid:
#        ERROR: no valid depth for chromosome ...
# ============================================================

my $config;
my $bam_list;
my $outdir = "results";
my $force  = 0;
my $help   = 0;

GetOptions(
    "config=s"   => \$config,
    "bam-list=s" => \$bam_list,
    "outdir=s"   => \$outdir,
    "force"      => \$force,
    "help"       => \$help,
) or die usage();

if ($help) {
    print usage();
    exit 0;
}

die usage() unless $config && $bam_list;

$config = abs_path($config);
die "[ERROR] Config file not found: $config\n" unless $config && -s $config;

$bam_list = abs_path($bam_list);
die "[ERROR] BAM list file not found: $bam_list\n" unless $bam_list && -s $bam_list;

my %CONF = read_config($config);

my $perl     = get_conf(\%CONF, "PERL", "perl");
my $keep_tmp = normalize_bool(get_conf(\%CONF, "KEEP_TMP", 0));

# CUSUM and calc_depth_ratio.pl are run on per-gene base-level depth files
# generated by run_gene_mean_depth.pl. These files must be retained.
my $keep_gene_depth_file = normalize_bool(get_conf(\%CONF, "KEEP_GENE_DEPTH_FILE", 1));
die "[ERROR] KEEP_GENE_DEPTH_FILE must be 1 when cusum_depth_del.pl and calc_depth_ratio.pl are enabled.\n"
  . "        Please set KEEP_GENE_DEPTH_FILE=1 in the config file.\n"
    unless $keep_gene_depth_file;

# ------------------------------------------------------------
# CUSUM parameters
#
# These three parameters must be defined in config file:
#   CUSUM_BASELINE
#   CUSUM_K
#   CUSUM_H
#
# No default values are set here, so they can only be modified
# from one place: the config file.
# ------------------------------------------------------------
my %CUSUM = (
    bin_size      => get_conf(\%CONF, "CUSUM_BIN_SIZE", 1),

    baseline      => get_conf_required(\%CONF, "CUSUM_BASELINE"),
    k             => get_conf_required(\%CONF, "CUSUM_K"),
    h             => get_conf_required(\%CONF, "CUSUM_H"),

    edge_ratio    => get_conf(\%CONF, "CUSUM_EDGE_RATIO", 0.80),
    recover_ratio => get_conf(\%CONF, "CUSUM_RECOVER_RATIO", 0.80),
    recover_bins  => get_conf(\%CONF, "CUSUM_RECOVER_BINS", 3),
    del_ratio     => get_conf(\%CONF, "CUSUM_DEL_RATIO", get_conf(\%CONF, "DEL_DEPTH_RATIO_CUTOFF", 0.65)),
    min_bins      => get_conf(\%CONF, "CUSUM_MIN_BINS", get_conf(\%CONF, "MIN_CONSECUTIVE_DEL_WINDOWS", 3)),
    min_len       => get_conf(\%CONF, "CUSUM_MIN_LEN", 1),
);

validate_cusum_params(\%CUSUM);

my $project_root = detect_project_root($config);

my $exon_txt = resolve_config_path(
    get_conf_required(\%CONF, "REFSEQ_MANE_SELECT_EXON_TXT"),
    $project_root
);

my $gene_txt = resolve_config_path(
    get_conf_required(\%CONF, "REFSEQ_MANE_SELECT_GENE_TXT"),
    $project_root
);

die "[ERROR] REFSEQ_MANE_SELECT_EXON_TXT file not found: $exon_txt\n"
    unless -s $exon_txt;

die "[ERROR] REFSEQ_MANE_SELECT_GENE_TXT file not found: $gene_txt\n"
    unless -s $gene_txt;

check_exon_txt_format($exon_txt);
check_gene_txt_format($gene_txt);

$outdir = abs_path($outdir) || $outdir;
make_path($outdir) unless -d $outdir;
$outdir = abs_path($outdir);

my %SCRIPT = (
    depth         => "$Bin/bin/run_gene_mean_depth.pl",
    cusum_depth   => "$Bin/bin/cusum_depth_del.pl",
    calc_ratio    => "$Bin/bin/calc_depth_ratio.pl",
    plot_depth    => "$Bin/bin/plot_depth_ratio.py",
    split_extract => "$Bin/bin/extract_sa_split_reads.pl",
    split_cluster => "$Bin/bin/cluster_sa_split_reads.pl",
    tlen_extract  => "$Bin/bin/extract_valid_tlen.pl",
    tlen_plot     => "$Bin/bin/plot_tlen_distribution.py",
    discordant    => "$Bin/bin/run_discordant_reads.pl",
    merge         => "$Bin/bin/merge_evidence.pl",
    extract_bam   => "$Bin/bin/extract_candidate_gene_bam.pl",
    annotate      => "$Bin/bin/annotate_candidates.pl",
);

foreach my $key (sort keys %SCRIPT) {
    check_script($SCRIPT{$key});
}

my @samples = read_bam_list($bam_list);
die "[ERROR] No valid sample found in BAM list: $bam_list\n" unless @samples;

print_summary(
    config       => $config,
    project_root => $project_root,
    bam_list     => $bam_list,
    exon_txt     => $exon_txt,
    gene_txt     => $gene_txt,
    outdir       => $outdir,
    keep_tmp     => $keep_tmp,
    cusum_ref    => \%CUSUM,
    sample_num   => scalar(@samples),
);

foreach my $item (@samples) {
    my $sample = $item->{sample};
    my $bam    = $item->{bam};

    my %DIR = prepare_sample_dirs($outdir, $sample, $force);

    my %OUT = (
        depth                   => "$DIR{depth}/$sample.depth_candidates.tsv",
        all_window_ratio        => "$DIR{depth}/$sample.depth_candidates.all_window_ratio.tsv",
        depth_plot_pdf          => "$DIR{depth}/$sample.window_del.per_gene.pdf",

        gene_depth_dir          => "$DIR{depth}/$sample.depth_candidates.gene_depth_files",

        cusum_dir               => "$DIR{depth}/$sample.depth_candidates.cusum",
        cusum_all               => "$DIR{depth}/$sample.depth_candidates.cusum.all.tsv",
        cusum_step_shell        => "$DIR{tmp}/$sample.step1b.cusum_depth_del.sh",

        base_depth_ratio_dir    => "$DIR{depth}/$sample.depth_candidates.base_depth_ratio",
        base_depth_ratio_all    => "$DIR{depth}/$sample.depth_candidates.base_depth_ratio.all.tsv",
        base_depth_summary_all  => "$DIR{depth}/$sample.depth_candidates.base_depth.summary.all.tsv",
        ratio_step_shell        => "$DIR{tmp}/$sample.step1c.calc_depth_ratio.sh",

        split_raw               => "$DIR{split}/$sample.split_reads.tsv",
        split_cluster           => "$DIR{split}/$sample.split_reads.clusters.tsv",

        valid_tlen              => "$DIR{discordant}/$sample.valid_tlen.tsv",
        tlen_plot_pdf           => "$DIR{discordant}/$sample.tlen_distribution.pdf",

        discordant              => "$DIR{discordant}/$sample.discordant_reads.tsv",

        merged                  => "$DIR{candidate}/$sample.merged_candidates.tsv",
        annotated               => "$DIR{report}/$sample.annotated_candidates.tsv",
    );

    my $sample_shell = "$DIR{sample}/$sample.run.sh";

    write_sample_shell(
        shell      => $sample_shell,
        sample     => $sample,
        bam        => $bam,
        config     => $config,
        exon_txt   => $exon_txt,
        gene_txt   => $gene_txt,
        perl       => $perl,
        keep_tmp   => $keep_tmp,
        cusum_ref  => \%CUSUM,
        script_ref => \%SCRIPT,
        dir_ref    => \%DIR,
        out_ref    => \%OUT,
    );

    chmod 0755, $sample_shell
        or die "[ERROR] Cannot chmod sample shell: $sample_shell\n";

    print "[INFO] Sample shell generated: $sample_shell\n";
}

print "\n";
print "[INFO] All sample shells generated successfully\n";
print "\n";
print "Run example:\n";
print "  bash $outdir/SAMPLE/SAMPLE.run.sh\n\n";

exit 0;

# ============================================================
# Main shell writer
# ============================================================

sub write_sample_shell {
    my %args = @_;

    my $shell      = $args{shell};
    my $sample     = $args{sample};
    my $bam        = $args{bam};
    my $config     = $args{config};
    my $exon_txt   = $args{exon_txt};
    my $gene_txt   = $args{gene_txt};
    my $perl       = $args{perl};
    my $keep_tmp   = $args{keep_tmp};
    my $cusum_ref  = $args{cusum_ref};
    my $script_ref = $args{script_ref};
    my $dir_ref    = $args{dir_ref};
    my $out_ref    = $args{out_ref};

    write_step1b_cusum_shell(
        shell     => $out_ref->{cusum_step_shell},
        perl      => $perl,
        script    => $script_ref->{cusum_depth},
        out_ref   => $out_ref,
        cusum_ref => $cusum_ref,
    );

    write_step1c_ratio_shell(
        shell   => $out_ref->{ratio_step_shell},
        perl    => $perl,
        script  => $script_ref->{calc_ratio},
        out_ref => $out_ref,
    );

    open my $SH, ">", $shell
        or die "[ERROR] Cannot write sample shell: $shell\n";

    write_header(
        fh       => $SH,
        sample   => $sample,
        config   => $config,
        bam      => $bam,
        exon_txt => $exon_txt,
        gene_txt => $gene_txt,
        outdir   => $dir_ref->{sample},
    );

    my $mkdir_cmd = join(
        " ",
        "mkdir -p",
        shell_quote($dir_ref->{log}),
        shell_quote($dir_ref->{depth}),
        shell_quote($out_ref->{cusum_dir}),
        shell_quote($out_ref->{base_depth_ratio_dir}),
        shell_quote($dir_ref->{split}),
        shell_quote($dir_ref->{discordant}),
        shell_quote($dir_ref->{candidate}),
        shell_quote($dir_ref->{gene_bam}),
        shell_quote($dir_ref->{report}),
        shell_quote($dir_ref->{tmp}),
    );

    write_block($SH, "Start sample: $sample");
    print $SH "$mkdir_cmd\n\n";

    my $cmd;

    # ------------------------------------------------------------
    # Step 1. Depth candidates
    # ------------------------------------------------------------
    $cmd = join(
        " ",
        shell_quote($perl),
        shell_quote($script_ref->{depth}),
        "--config", shell_quote($config),
        "--bam",    shell_quote($bam),
        "--sample", shell_quote($sample),
        "--out",    shell_quote($out_ref->{depth}),
    );

    write_cmd(
        $SH,
        "Step 1: gene_mean_depth",
        $cmd,
        "$dir_ref->{log}/01.gene_mean_depth.log"
    );

    # ------------------------------------------------------------
    # Step 1b. CUSUM depth deletion calling
    # ------------------------------------------------------------
    $cmd = join(
        " ",
        "bash",
        shell_quote($out_ref->{cusum_step_shell}),
    );

    write_cmd(
        $SH,
        "Step 1b: cusum_depth_del",
        $cmd,
        "$dir_ref->{log}/01b.cusum_depth_del.log"
    );

    # ------------------------------------------------------------
    # Step 1c. Base-level depth ratio calculation
    # ------------------------------------------------------------
    $cmd = join(
        " ",
        "bash",
        shell_quote($out_ref->{ratio_step_shell}),
    );

    write_cmd(
        $SH,
        "Step 1c: calc_depth_ratio",
        $cmd,
        "$dir_ref->{log}/01c.calc_depth_ratio.log"
    );

    # ------------------------------------------------------------
    # Step 1d. Plot depth ratio
    # ------------------------------------------------------------
    $cmd = join(
        " ",
        "python3",
        shell_quote($script_ref->{plot_depth}),
        "--conf",   shell_quote($config),
        "--input",  shell_quote($out_ref->{all_window_ratio}),
        "--output", shell_quote($out_ref->{depth_plot_pdf}),
    );

    write_cmd(
        $SH,
        "Step 1d: plot_depth_ratio",
        $cmd,
        "$dir_ref->{log}/01d.plot_depth_ratio.log"
    );

    # ------------------------------------------------------------
    # Step 2. Extract SA split reads
    # ------------------------------------------------------------
    $cmd = join(
        " ",
        shell_quote($perl),
        shell_quote($script_ref->{split_extract}),
        "--conf",   shell_quote($config),
        "--bam",    shell_quote($bam),
        "--sample", shell_quote($sample),
        "--out",    shell_quote($out_ref->{split_raw}),
    );

    write_cmd(
        $SH,
        "Step 2: extract_sa_split_reads",
        $cmd,
        "$dir_ref->{log}/02.extract_sa_split_reads.log"
    );

    # ------------------------------------------------------------
    # Step 3. Cluster SA split reads
    # ------------------------------------------------------------
    $cmd = join(
        " ",
        shell_quote($perl),
        shell_quote($script_ref->{split_cluster}),
        "--conf",    shell_quote($config),
        "--input",   shell_quote($out_ref->{split_raw}),
        "--outfile", shell_quote($out_ref->{split_cluster}),
    );

    write_cmd(
        $SH,
        "Step 3: cluster_sa_split_reads",
        $cmd,
        "$dir_ref->{log}/03.cluster_sa_split_reads.log"
    );

    # ------------------------------------------------------------
    # Step 3b. Extract valid TLEN
    # ------------------------------------------------------------
    $cmd = join(
        " ",
        shell_quote($perl),
        shell_quote($script_ref->{tlen_extract}),
        shell_quote($bam),
        shell_quote($out_ref->{valid_tlen}),
    );

    write_cmd(
        $SH,
        "Step 3b: extract_valid_tlen",
        $cmd,
        "$dir_ref->{log}/03b.extract_valid_tlen.log"
    );

    # ------------------------------------------------------------
    # Step 3c. Plot TLEN distribution
    # ------------------------------------------------------------
    $cmd = join(
        " ",
        "python",
        shell_quote($script_ref->{tlen_plot}),
        shell_quote($out_ref->{valid_tlen}),
        shell_quote($out_ref->{tlen_plot_pdf}),
    );

    write_cmd(
        $SH,
        "Step 3c: plot_tlen_distribution",
        $cmd,
        "$dir_ref->{log}/03c.plot_tlen_distribution.log"
    );

    # ------------------------------------------------------------
    # Step 4. Discordant reads
    # ------------------------------------------------------------
    $cmd = join(
        " ",
        shell_quote($perl),
        shell_quote($script_ref->{discordant}),
        "--config", shell_quote($config),
        "--bam",    shell_quote($bam),
        "--sample", shell_quote($sample),
        "--out",    shell_quote($out_ref->{discordant}),
    );

    write_cmd(
        $SH,
        "Step 4: discordant_reads",
        $cmd,
        "$dir_ref->{log}/04.discordant_reads.log"
    );

    # ------------------------------------------------------------
    # Step 5. Merge evidence
    # ------------------------------------------------------------
    $cmd = join(
        " ",
        shell_quote($perl),
        shell_quote($script_ref->{merge}),
        "--config",     shell_quote($config),
        "--sample",     shell_quote($sample),
        "--depth",      shell_quote($out_ref->{depth}),
        "--split",      shell_quote($out_ref->{split_cluster}),
        "--discordant", shell_quote($out_ref->{discordant}),
        "--out",        shell_quote($out_ref->{merged}),
    );

    write_cmd(
        $SH,
        "Step 5: merge_evidence",
        $cmd,
        "$dir_ref->{log}/05.merge_evidence.log"
    );

    # ------------------------------------------------------------
    # Step 6. Extract candidate gene BAM
    # ------------------------------------------------------------
    $cmd = join(
        " ",
        shell_quote($perl),
        shell_quote($script_ref->{extract_bam}),
        "--config",    shell_quote($config),
        "--candidate", shell_quote($out_ref->{merged}),
        "--bam",       shell_quote($bam),
        "--outdir",    shell_quote($dir_ref->{gene_bam}),
    );

    write_cmd(
        $SH,
        "Step 6: extract_candidate_gene_bam",
        $cmd,
        "$dir_ref->{log}/06.extract_candidate_gene_bam.log"
    );

    # ------------------------------------------------------------
    # Step 7. Annotate candidates
    # ------------------------------------------------------------
    $cmd = join(
        " ",
        shell_quote($perl),
        shell_quote($script_ref->{annotate}),
        "--config", shell_quote($config),
        "--input",  shell_quote($out_ref->{merged}),
        "--out",    shell_quote($out_ref->{annotated}),
    );

    write_cmd(
        $SH,
        "Step 7: annotate_candidates",
        $cmd,
        "$dir_ref->{log}/07.annotate_candidates.log"
    );

    if (!$keep_tmp) {
        print $SH "rm -rf " . shell_quote($dir_ref->{tmp}) . "\n\n";
    }

    print $SH "echo \"[INFO] Finished sample: $sample \$(date)\"\n";
    print $SH "echo \"[INFO] Depth candidates       : $out_ref->{depth}\"\n";
    print $SH "echo \"[INFO] CUSUM depth calls      : $out_ref->{cusum_all}\"\n";
    print $SH "echo \"[INFO] Base depth ratio       : $out_ref->{base_depth_ratio_all}\"\n";
    print $SH "echo \"[INFO] Base depth summary     : $out_ref->{base_depth_summary_all}\"\n";
    print $SH "echo \"[INFO] Raw split reads        : $out_ref->{split_raw}\"\n";
    print $SH "echo \"[INFO] Split clusters        : $out_ref->{split_cluster}\"\n";
    print $SH "echo \"[INFO] Discordant candidates : $out_ref->{discordant}\"\n";
    print $SH "echo \"[INFO] Merged candidates     : $out_ref->{merged}\"\n";
    print $SH "echo \"[INFO] Candidate gene BAM dir: $dir_ref->{gene_bam}\"\n";
    print $SH "echo \"[INFO] Annotated candidates  : $out_ref->{annotated}\"\n";

    close $SH;
}

sub write_header {
    my %args = @_;

    my $FH     = $args{fh};
    my $sample = $args{sample};
    my $config = $args{config};
    my $bam    = $args{bam};
    my $exon   = $args{exon_txt};
    my $gene   = $args{gene_txt};
    my $outdir = $args{outdir};

    print $FH <<"HEADER";
#!/usr/bin/env bash
set -euo pipefail

############################################################
# Auto-generated by HCMExonDel.pl
# Sample    : $sample
# Config    : $config
# BAM       : $bam
# Exon TXT  : $exon
# Gene TXT  : $gene
# Outdir    : $outdir
#
# Workflow:
#   1.  gene_mean_depth
#   1b. cusum_depth_del
#   1c. calc_depth_ratio
#   1d. plot_depth_ratio
#   2.  extract_sa_split_reads
#   3.  cluster_sa_split_reads
#   3b. extract_valid_tlen
#   3c. plot_tlen_distribution
#   4.  discordant_reads
#   5.  merge_evidence
#   6.  extract_candidate_gene_bam
#   7.  annotate_candidates
############################################################

HEADER
}

sub write_block {
    my ($fh, $message) = @_;
    print $fh "echo \"[INFO] $message \$(date)\"\n";
}

sub write_cmd {
    my ($fh, $message, $cmd, $log) = @_;
    print $fh "echo \"[INFO] $message \$(date)\"\n";
    print $fh "$cmd > " . shell_quote($log) . " 2>&1\n\n";
}

sub write_step1b_cusum_shell {
    my %args = @_;

    my $shell     = $args{shell};
    my $perl      = shell_quote($args{perl});
    my $script    = shell_quote($args{script});
    my $out_ref   = $args{out_ref};
    my $cusum_ref = $args{cusum_ref};

    my $gene_depth_dir = shell_quote($out_ref->{gene_depth_dir});
    my $cusum_dir      = shell_quote($out_ref->{cusum_dir});
    my $cusum_all      = shell_quote($out_ref->{cusum_all});

    my $cusum_args = join(
        " ",
        "--bin-size",      shell_quote($cusum_ref->{bin_size}),
        "--baseline",      shell_quote($cusum_ref->{baseline}),
        "--k",             shell_quote($cusum_ref->{k}),
        "--h",             shell_quote($cusum_ref->{h}),
        "--edge-ratio",    shell_quote($cusum_ref->{edge_ratio}),
        "--recover-ratio", shell_quote($cusum_ref->{recover_ratio}),
        "--recover-bins",  shell_quote($cusum_ref->{recover_bins}),
        "--del-ratio",     shell_quote($cusum_ref->{del_ratio}),
        "--min-bins",      shell_quote($cusum_ref->{min_bins}),
        "--min-len",       shell_quote($cusum_ref->{min_len}),
    );

    open my $SH, ">", $shell
        or die "[ERROR] Cannot write Step 1b shell: $shell\n";

    print $SH <<"BASH";
#!/usr/bin/env bash
set -euo pipefail

GENE_DEPTH_DIR=$gene_depth_dir
CUSUM_DIR=$cusum_dir
CUSUM_ALL=$cusum_all

mkdir -p "\$CUSUM_DIR"

shopt -s nullglob
depth_files=("\$GENE_DEPTH_DIR"/*.tsv)

if [ \${#depth_files[\@]} -eq 0 ]; then
    echo "[ERROR] No per-gene depth files found: \$GENE_DEPTH_DIR"
    echo "[ERROR] Please set KEEP_GENE_DEPTH_FILE=1 in the config file."
    exit 1
fi

printf "Depth_File\\tCHROM\\tSTART\\tEND\\tLENGTH\\tN_BINS\\tBASELINE\\tMEAN_DEPTH\\tMEAN_RATIO\\tMIN_RATIO\\tMAX_CUSUM\\tTYPE\\n" > "\$CUSUM_ALL"

for depth_file in "\${depth_files[\@]}"; do
    base=\$(basename "\$depth_file")
    prefix=\${base%.tsv}
    out_file="\$CUSUM_DIR/\${prefix}.cusum_del.tsv"

    valid_depth_count=\$(
        awk '
            BEGIN { n = 0 }
            /^#/ { next }
            NF < 3 { next }
            \$2 !~ /^[0-9]+\$/ { next }
            \$3 !~ /^-?[0-9]+(\\.[0-9]+)?\$/ { next }
            \$3 > 0 { n++ }
            END { print n + 0 }
        ' "\$depth_file"
    )

    if [ "\$valid_depth_count" -eq 0 ]; then
        echo "[WARN] Skip CUSUM because no positive depth found: \$depth_file"

        printf "CHROM\\tSTART\\tEND\\tLENGTH\\tN_BINS\\tBASELINE\\tMEAN_DEPTH\\tMEAN_RATIO\\tMIN_RATIO\\tMAX_CUSUM\\tTYPE\\n" > "\$out_file"

        continue
    fi

    $perl $script \\
        --in "\$depth_file" \\
        --out "\$out_file" \\
        $cusum_args

    awk -v src="\$base" '
        BEGIN { FS = OFS = "\\t" }
        NR > 1 { print src, \$0 }
    ' "\$out_file" >> "\$CUSUM_ALL"
done

echo "[INFO] CUSUM per-gene output directory: \$CUSUM_DIR"
echo "[INFO] CUSUM merged output: \$CUSUM_ALL"

BASH

    close $SH;

    chmod 0755, $shell
        or die "[ERROR] Cannot chmod Step 1b shell: $shell\n";
}

sub write_step1c_ratio_shell {
    my %args = @_;

    my $shell   = $args{shell};
    my $perl    = shell_quote($args{perl});
    my $script  = shell_quote($args{script});
    my $out_ref = $args{out_ref};

    my $gene_depth_dir = shell_quote($out_ref->{gene_depth_dir});
    my $ratio_dir      = shell_quote($out_ref->{base_depth_ratio_dir});
    my $ratio_all      = shell_quote($out_ref->{base_depth_ratio_all});
    my $summary_all    = shell_quote($out_ref->{base_depth_summary_all});

    open my $SH, ">", $shell
        or die "[ERROR] Cannot write Step 1c shell: $shell\n";

    print $SH <<"BASH";
#!/usr/bin/env bash
set -euo pipefail

GENE_DEPTH_DIR=$gene_depth_dir
RATIO_DIR=$ratio_dir
RATIO_ALL=$ratio_all
SUMMARY_ALL=$summary_all

mkdir -p "\$RATIO_DIR"

shopt -s nullglob
depth_files=("\$GENE_DEPTH_DIR"/*.tsv)

if [ \${#depth_files[\@]} -eq 0 ]; then
    echo "[ERROR] No per-gene depth files found: \$GENE_DEPTH_DIR"
    echo "[ERROR] Please set KEEP_GENE_DEPTH_FILE=1 in the config file."
    exit 1
fi

printf "Depth_File\\t#CHROM\\tPOS\\tDepth\\tMedian_Depth\\tMean_Depth\\tRatio_By_Median\\tRatio_By_Mean\\n" > "\$RATIO_ALL"
printf "Depth_File\\tMetric\\tValue\\n" > "\$SUMMARY_ALL"

for depth_file in "\${depth_files[\@]}"; do
    base=\$(basename "\$depth_file")
    prefix=\${base%.tsv}
    ratio_file="\$RATIO_DIR/\${prefix}.depth_ratio.tsv"
    summary_file="\$RATIO_DIR/\${prefix}.depth_summary.tsv"

    valid_record_count=\$(
        awk '
            BEGIN { n = 0 }
            /^#/ { next }
            NF < 3 { next }
            \$2 !~ /^[0-9]+\$/ { next }
            \$3 !~ /^-?[0-9]+(\\.[0-9]+)?\$/ { next }
            { n++ }
            END { print n + 0 }
        ' "\$depth_file"
    )

    if [ "\$valid_record_count" -eq 0 ]; then
        echo "[WARN] Skip calc_depth_ratio because no valid depth record found: \$depth_file"

        printf "#CHROM\\tPOS\\tDepth\\tMedian_Depth\\tMean_Depth\\tRatio_By_Median\\tRatio_By_Mean\\n" > "\$ratio_file"
        printf "Metric\\tValue\\n" > "\$summary_file"
        printf "Total_Sites\\t0\\n" >> "\$summary_file"
        printf "Median_Depth\\tNA\\n" >> "\$summary_file"
        printf "Mean_Depth\\tNA\\n" >> "\$summary_file"

        awk -v src="\$base" '
            BEGIN { FS = OFS = "\\t" }
            NR > 1 { print src, \$1, \$2 }
        ' "\$summary_file" >> "\$SUMMARY_ALL"

        continue
    fi

    $perl $script "\$depth_file" "\$ratio_file" "\$summary_file"

    awk -v src="\$base" '
        BEGIN { FS = OFS = "\\t" }
        NR > 1 { print src, \$0 }
    ' "\$ratio_file" >> "\$RATIO_ALL"

    awk -v src="\$base" '
        BEGIN { FS = OFS = "\\t" }
        NR > 1 { print src, \$1, \$2 }
    ' "\$summary_file" >> "\$SUMMARY_ALL"
done

echo "[INFO] Base-depth ratio per-gene output directory: \$RATIO_DIR"
echo "[INFO] Base-depth ratio merged output: \$RATIO_ALL"
echo "[INFO] Base-depth summary merged output: \$SUMMARY_ALL"

BASH

    close $SH;

    chmod 0755, $shell
        or die "[ERROR] Cannot chmod Step 1c shell: $shell\n";
}

